export function formatCurrency(amountUSD: number, country: AfricanCountry): string {
  const converted = amountUSD * country.exchangeRateToUSD;
  // Format with thousand separators
  const rounded = country.exchangeRateToUSD > 50 ? Math.round(converted) : Number(converted.toFixed(2));
  return `${country.currencySymbol} ${rounded.toLocaleString()}`;
}

export function convertAmount(amountUSD: number, country: AfricanCountry): number {
  const converted = amountUSD * country.exchangeRateToUSD;
  return country.exchangeRateToUSD > 50 ? Math.round(converted) : Number(converted.toFixed(2));
}
